import { useMemo, useState } from 'react';
import { ArrowLeft, Printer } from 'lucide-react';
import { computeScenarios, quoteTotal } from '../domain/budget';
import {
  SCENARIO_LABEL,
  SETTING_LABEL,
  TASK_STATUS_LABEL,
  VENDOR_STATUS_LABEL,
  VENUE_STATUS_LABEL,
  categoryMeta,
  eventTypeLabel,
  workstreamLabel,
} from '../domain/catalog';
import { summarizeGuests } from '../domain/guests';
import { analyzeRunOfShow, sortRunItems } from '../domain/runOfShow';
import type { EventPlan, ScenarioKey } from '../domain/types';
import { addDays, formatDate, formatDateTime, formatMoney, formatMoneyCompact } from '../domain/util';
import { hrefFor } from '../lib/router';
import { useInsights, useToday } from './common';

const TITLES: Record<string, string> = {
  brief: 'Event brief',
  budget: 'Budget report',
  timeline: 'Timeline & milestone checklist',
  vendors: 'Vendor shortlist & quotations',
  runofshow: 'Run of show',
};

export function ReportView({ plan, kind }: { plan: EventPlan; kind: string }) {
  const [rsvp, setRsvp] = useState(true);
  const title = TITLES[kind] ?? TITLES.brief;
  const back = hrefFor({
    name: 'view',
    eventId: plan.id,
    view:
      kind === 'brief'
        ? 'brief'
        : kind === 'runofshow'
          ? 'runofshow'
          : kind === 'vendors'
            ? 'vendors'
            : kind === 'timeline'
              ? 'timeline'
              : kind === 'budget'
                ? 'budget'
                : 'exports',
  });
  return (
    <div>
      <div className="report-toolbar">
        <a className="btn" href={back}>
          <ArrowLeft /> Back to workspace
        </a>
        <div className="row-wrap">
          {kind === 'brief' && plan.guests.length > 0 && (
            <label className="check small">
              <input type="checkbox" checked={rsvp} onChange={(e) => setRsvp(e.target.checked)} /> Include RSVP totals (no names)
            </label>
          )}
          <button className="btn btn-primary" onClick={() => window.print()}>
            <Printer /> Print / Save as PDF
          </button>
        </div>
      </div>
      <article className="report" aria-label={title}>
        <div className="eyebrow">
          {eventTypeLabel(plan.brief.type, plan.brief.customTypeLabel)} · {plan.brief.city}
          {plan.isDemo ? ' · Illustrative demo' : ''}
        </div>
        <h1 style={{ marginTop: 6 }}>{plan.brief.name}</h1>
        <div className="ink-2" style={{ marginTop: 6 }}>
          {title} · {formatDate(plan.brief.eventDate, { weekday: true })} · {plan.brief.guestCount} guests · prepared by{' '}
          {plan.brief.plannerName || 'the planning team'}
        </div>
        {kind === 'budget' ? (
          <BudgetReport plan={plan} />
        ) : kind === 'timeline' ? (
          <TimelineReport plan={plan} />
        ) : kind === 'vendors' ? (
          <VendorReport plan={plan} />
        ) : kind === 'runofshow' ? (
          <RunReport plan={plan} />
        ) : (
          <BriefReport plan={plan} rsvp={rsvp} />
        )}
        <div className="report-footer">
          Generated by Sutrā Studio on {formatDateTime(new Date().toISOString())} from the current plan. Budget figures marked as estimates
          are illustrative planning benchmarks, not market quotations.
          {plan.vendors.some((v) => v.verification.level === 'illustrative')
            ? ' Vendors labelled “demo” are fictional and unverified.'
            : ''}
        </div>
      </article>
    </div>
  );
}

