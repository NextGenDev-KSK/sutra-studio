function BudgetReport({ plan }: { plan: EventPlan }) {
  const today = useToday();
  const ins = useInsights(plan);
  const b = ins.budget;
  const cur = plan.brief.currency;
  const sc = useMemo(() => computeScenarios(plan, today), [plan, today]);
  const keys: ScenarioKey[] = ['lean', 'balanced', 'premium'];
  return (
    <>
      <h2>Summary</h2>
      <table className="table">
        <tbody>
          <tr>
            <td>Budget ceiling</td>
            <td className="r">{formatMoney(b.ceiling, cur)}</td>
          </tr>
          <tr>
            <td>Forecast total (incl. {b.contingencyPct}% contingency)</td>
            <td className="r">{formatMoney(b.forecastTotal, cur)}</td>
          </tr>
          <tr>
            <td>Remaining</td>
            <td className="r">{formatMoney(b.remaining, cur)}</td>
          </tr>
          <tr>
            <td>Committed / paid / outstanding</td>
            <td className="r">
              {formatMoney(b.committedTotal, cur)} / {formatMoney(b.paidTotal, cur)} / {formatMoney(b.outstandingTotal, cur)}
            </td>
          </tr>
          <tr>
            <td>Cost per guest</td>
            <td className="r">{formatMoney(b.costPerGuest, cur)}</td>
          </tr>
        </tbody>
      </table>
      <h2>Itemised budget</h2>
      <table className="table">
        <thead>
          <tr>
            <th>Category</th>
            <th className="r">Planned</th>
            <th className="r">Committed</th>
            <th className="r">Paid</th>
            <th className="r">Forecast</th>
            <th className="r">Variance</th>
          </tr>
        </thead>
        <tbody>
          {b.lines.map((l) => (
            <tr key={l.key}>
              <td>
                {l.label}
                <div className="cell-sub">
                  {l.source === 'committed' ? 'Contract' : l.source === 'quote' ? 'Preferred quote' : 'Estimate'}
                </div>
              </td>
              <td className="r">{formatMoney(l.plannedTotal, cur)}</td>
              <td className="r">{formatMoney(l.committed, cur)}</td>
              <td className="r">{formatMoney(l.paid, cur)}</td>
              <td className="r">{formatMoney(l.forecast, cur)}</td>
              <td className="r">{formatMoney(l.variance, cur)}</td>
            </tr>
          ))}
          <tr className="row-total">
            <td>Contingency</td>
            <td className="r">{formatMoney(b.plannedContingency, cur)}</td>
            <td />
            <td />
            <td className="r">{formatMoney(b.contingency, cur)}</td>
            <td />
          </tr>
          <tr className="row-total">
            <td>Total</td>
            <td className="r">{formatMoney(b.plannedTotal, cur)}</td>
            <td className="r">{formatMoney(b.committedTotal, cur)}</td>
            <td className="r">{formatMoney(b.paidTotal, cur)}</td>
            <td className="r">{formatMoney(b.forecastTotal, cur)}</td>
            <td />
          </tr>
        </tbody>
      </table>
      <h2>Scenario comparison</h2>
      <table className="table">
        <thead>
          <tr>
            <th>Category</th>
            {keys.map((k) => (
              <th key={k} className="r">
                {SCENARIO_LABEL[k]}
              </th>
            ))}
          </tr>
        </thead>
        <tbody>
          {plan.budget.categories.map((c) => (
            <tr key={c.key}>
              <td>{c.label}</td>
              {keys.map((k) => (
                <td key={k} className="r">
                  {formatMoneyCompact(sc[k].lines.find((l) => l.key === c.key)?.total ?? 0, cur)}
                </td>
              ))}
            </tr>
          ))}
          <tr className="row-total">
            <td>Total incl. contingency</td>
            {keys.map((k) => (
              <td key={k} className="r">
                {formatMoneyCompact(sc[k].total, cur)}
              </td>
            ))}
          </tr>
          <tr>
            <td>Per guest</td>
            {keys.map((k) => (
              <td key={k} className="r">
                {formatMoneyCompact(sc[k].perGuest, cur)}
              </td>
            ))}
          </tr>
        </tbody>
      </table>
      {keys.map((k) => (
        <div key={k}>
          <h3 style={{ marginTop: 14 }}>{SCENARIO_LABEL[k]} trade-offs</h3>
          <ul className="bullets small">
            {sc[k].tradeoffs.map((t) => (
              <li key={t}>{t}</li>
            ))}
          </ul>
        </div>
      ))}
      {b.payments.length > 0 && (
        <>
          <h2>Payment schedule</h2>
          <table className="table">
            <thead>
              <tr>
                <th>Payment</th>
                <th>Vendor</th>
                <th className="r">Amount</th>
                <th>Due</th>
                <th>Status</th>
              </tr>
            </thead>
            <tbody>
              {b.payments.map((p) => (
                <tr key={p.id}>
                  <td>{p.label}</td>
                  <td>{p.vendorName}</td>
                  <td className="r">{formatMoney(p.amount, cur)}</td>
                  <td>{formatDate(p.dueDate)}</td>
                  <td>{p.status}</td>
                </tr>
              ))}
            </tbody>
          </table>
        </>
      )}
    </>
  );
}

function TimelineReport({ plan }: { plan: EventPlan }) {
  const ins = useInsights(plan);
  const team = new Map(plan.team.map((m) => [m.id, m.name]));
  return (
    <>
      <h2>Progress</h2>
      <p>
        {ins.timeline.done} of {ins.timeline.total} tasks complete ({ins.timeline.pct}%) · {ins.timeline.overdue.length} overdue ·{' '}
        {ins.timeline.daysToEvent} days to go.
      </p>
      <h2>Checklist</h2>
      <table className="table">
        <thead>
          <tr>
            <th style={{ width: 24 }}>✓</th>
            <th>Task</th>
            <th>Owner</th>
            <th>Due</th>
            <th>Status</th>
          </tr>
        </thead>
        <tbody>
          {ins.timeline.ordered.map((t) => (
            <tr key={t.id}>
              <td>{t.status === 'done' ? '☑' : '☐'}</td>
              <td>
                {t.milestone ? '◆ ' : ''}
                {t.title}
                <div className="cell-sub">
                  {workstreamLabel(t.workstream)}
                  {ins.timeline.insights.get(t.id)?.flags.length ? ` · ${ins.timeline.insights.get(t.id)!.flags.join('; ')}` : ''}
                </div>
              </td>
              <td>{t.ownerId ? team.get(t.ownerId) : '—'}</td>
              <td className="nowrap">{formatDate(t.dueDate)}</td>
              <td>{TASK_STATUS_LABEL[t.status]}</td>
            </tr>
          ))}
        </tbody>
      </table>
    </>
  );
}

function VendorReport({ plan }: { plan: EventPlan }) {
  const cur = plan.brief.currency;
  const cats = [...new Set(plan.vendors.map((v) => v.category))];
  return (
    <>
      {cats.map((c) => (
        <div key={c}>
          <h2>{categoryMeta(c)?.vendorLabel ?? c}</h2>
          <table className="table">
            <thead>
              <tr>
                <th>Vendor</th>
                <th>Status</th>
                <th className="r">Quote</th>
                <th>Included</th>
                <th>Verification</th>
              </tr>
            </thead>
            <tbody>
              {plan.vendors
                .filter((v) => v.category === c)
                .map((v) => (
                  <tr key={v.id}>
                    <td>
                      {v.name}
                      {v.preferred ? ' ★' : ''}
                      <div className="cell-sub">{[...v.pros.map((p) => `+ ${p}`), ...v.cons.map((p) => `– ${p}`)].join(' · ')}</div>
                    </td>
                    <td>{VENDOR_STATUS_LABEL[v.status]}</td>
                    <td className="r">{v.quote ? formatMoney(quoteTotal(v.quote, plan.brief.guestCount), cur) : '—'}</td>
                    <td className="small">{v.quote?.deliverables ?? '—'}</td>
                    <td className="small">
                      {v.verification.level === 'verified'
                        ? `Verified ${v.verification.checkedOn ?? ''}${v.verification.sourceUrl ? ` · ${v.verification.sourceUrl}` : ''}`
                        : v.verification.level === 'illustrative'
                          ? 'Illustrative demo — not verified'
                          : 'Not verified'}
                    </td>
                  </tr>
                ))}
            </tbody>
          </table>
        </div>
      ))}
      {!plan.vendors.length && <p className="muted">No vendors recorded.</p>}
    </>
  );
}

function RunReport({ plan }: { plan: EventPlan }) {
  const team = new Map(plan.team.map((m) => [m.id, m.name]));
  const vendors = new Map(plan.vendors.map((v) => [v.id, v.name]));
  const issues = analyzeRunOfShow(plan);
  const days = [...new Set(plan.runOfShow.map((r) => r.dayIndex))].sort((a, b) => a - b);
  return (
    <>
      {days.map((d) => (
        <div key={d}>
          <h2>
            Day {d + 1} — {formatDate(addDays(plan.brief.eventDate, d), { weekday: true })}
            {plan.daySettings.find((x) => x.dayIndex === d)?.soundCutoff
              ? ` · sound cut-off ${plan.daySettings.find((x) => x.dayIndex === d)!.soundCutoff}`
              : ''}
          </h2>
          <table className="table">
            <thead>
              <tr>
                <th>Time</th>
                <th>Activity</th>
                <th>Location</th>
                <th>Lead</th>
                <th>Vendors</th>
                <th>Notes</th>
              </tr>
            </thead>
            <tbody>
              {sortRunItems(plan.runOfShow.filter((r) => r.dayIndex === d)).map((r) => (
                <tr key={r.id}>
                  <td className="nowrap num">
                    {r.start}–{r.end}
                    <div className="cell-sub">{r.timing === 'confirmed' ? 'Confirmed' : 'Suggested'}</div>
                  </td>
                  <td>
                    {r.title}
                    {issues
                      .filter((i) => i.itemId === r.id)
                      .map((i) => (
                        <div key={i.id} className="cell-sub" style={{ color: 'var(--danger)' }}>
                          ⚠ {i.message}
                        </div>
                      ))}
                  </td>
                  <td>{r.location}</td>
                  <td>{r.leadId ? team.get(r.leadId) : '—'}</td>
                  <td className="small">
                    {r.vendorIds
                      .map((id) => vendors.get(id))
                      .filter(Boolean)
                      .join(', ') || '—'}
                  </td>
                  <td className="small">
                    {r.setupMinutes ? `Setup ${r.setupMinutes} min. ` : ''}
                    {r.setupNotes}{' '}
                    {r.contingency && (
                      <>
                        <br />
                        <em>Contingency:</em> {r.contingency}
                      </>
                    )}
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      ))}
      {!days.length && <p className="muted">No run-of-show items yet.</p>}
    </>
  );
}
